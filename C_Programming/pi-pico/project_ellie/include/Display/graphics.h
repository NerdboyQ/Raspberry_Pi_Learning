/**
 * @brief Metadata for a GIF, including title, frame count, and dimensions.
 * 32bytes in total size
 */
typedef struct {
    uint8_t title[29];
    uint8_t frame_cnt, width, height;
} gif_meta_t;

#pragma pack(pop)

typedef struct {
    uint16_t height, width;
} sprite_dimensions_t;



typedef struct {
    uint16_t left, top, right, bottom;
} sprite_position_t;

/**
 * @brief Structure representing a sprite/gif-frame with image data, dimensions, and position.
 */
typedef struct {
    uint16_t *img;
	// Color Sprites/Frames will be RGB565 format (2 bytes/pixel)
    uint16_t array_length;
    sprite_dimensions_t dimensions;
    sprite_position_t position;
} sprite_t;

/**
 * GIF that stores frames/images for animation
 */
typedef struct {
	// Title of the gif (up to 31 characters + null terminator)
	uint8_t title[32];
    sprite_t *frames;
	// Color Sprites/Frames will be RGB565 format (2 bytes/pixel)
    uint16_t frame_cnt;
} gif_t;

